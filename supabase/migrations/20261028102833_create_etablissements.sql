-- Création de la table des établissements.
-- Un établissement correspond à un SIRET et à une comptabilité distincte.
-- Le statut « a_identifier » sert aux documents comptables qui ne peuvent
-- pas encore être rattachés à un établissement, ou qui concernent les deux.

create table public.etablissements (
  id bigint generated by default as identity primary key,
  code text not null unique,
  nom text not null,
  siret text unique,
  actif boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Données de référence.
-- « code » est l’identifiant technique.
-- « nom » est le nom affiché dans l’application.
